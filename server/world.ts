const LEGACY_CAVEAT = ' Это вывод внутри выбранного семейства, а не доказательство для всех возможных миров.';
function englishText(text: string): string {
  if (Object.hasOwn(LEGACY_ENGLISH, text)) return LEGACY_ENGLISH[text]!;
  const caveat = text.endsWith(LEGACY_CAVEAT);
  const core = caveat ? text.slice(0, -LEGACY_CAVEAT.length) : text;
  let translated: string | undefined;
  let match: RegExpMatchArray | null;
  if ((match = core.match(/^Опыт (\d+): (растение прижилось|растение не выжило), рост (\d+)\/100\. Потрачено (\d+) кредита\.$/))) {
    translated = `Experiment ${match[1]}: ${match[2] === 'растение прижилось' ? 'the plant survived' : 'the plant did not survive'}, growth ${match[3]}/100. Spent ${match[4]} credits.`;
  } else if ((match = core.match(/^Опыт (\d+): рост (\d+)\/100, энергия (\d+)\/100\. Потрачен 1 исследовательский кредит\.$/))) {
    translated = `Experiment ${match[1]}: growth ${match[2]}/100, energy ${match[3]}/100. Spent 1 research credit.`;
  } else if ((match = core.match(/^Список возможных объяснений сократился: (\d+) → (\d+)\.$/))) {
    translated = `Possible explanations narrowed: ${match[1]} → ${match[2]}.`;
  } else if ((match = core.match(/^Наблюдение исключило (\d+) моделей; осталось (\d+)\.$/))) {
    translated = `The observation ruled out ${match[1]} models; ${match[2]} remain.`;
  } else if ((match = core.match(/^(?:Ответ на воду[:.] )?Наблюдения поддерживают более высокий рост (с водой|без воды)\.$/))) {
    translated = `${core.startsWith('Ответ на воду') ? 'Water response. ' : ''}Observations support stronger growth ${match[1] === 'с водой' ? 'with water' : 'without water'}.`;
  } else if ((match = core.match(/^(?:Минеральный катализатор[:.] )?Все оставшиеся модели предсказывают лучший рост (без минералов|с базальтом|с кварцем)\.$/))) {
    const mineral = { 'без минералов': 'without minerals', 'с базальтом': 'with basalt', 'с кварцем': 'with quartz' }[match[1]!];
    translated = `${core.startsWith('Минеральный катализатор') ? 'Mineral catalyst. ' : ''}All remaining models predict stronger growth ${mineral}.`;
  } else if ((match = core.match(/^(?:Свет и температура[:.] )?В рамках семейства моделей предпочтительны (синий|янтарный) свет и (тепло|прохлада)\.$/))) {
    translated = `${core.startsWith('Свет и температура') ? 'Light and temperature. ' : ''}Within this model family, the preferred conditions are ${match[1] === 'синий' ? 'blue' : 'amber'} light and ${match[2] === 'тепло' ? 'warmth' : 'cool temperatures'}.`;
  } else if ((match = core.match(/^Независимая проверка: (\d+)\/(\d+) точных прогнозов\. Контрольные результаты не добавлены в обучающие наблюдения\.$/))) {
    translated = `Independent validation: ${match[1]}/${match[2]} exact predictions. Held-out results were not added to the training observations.`;
  }
  if (translated) return translated + (caveat ? ' This is an inference within the selected model family, not a proof for every possible world.' : '');
  // Preserve user and external IMD explanations verbatim when no exact legacy
  // template matches. Do not invent a translation or silently discard evidence.
  return /[А-Яа-яЁё]/.test(text) ? `Original text (untranslated): ${text}` : text;
}
