export class Expedition {
  #data: Snapshot;
  constructor(seed = randomBytes(24).toString('hex')) {
    if (typeof seed !== 'string' || seed.length === 0 || seed.length > 256) throw new ExpeditionError('BAD_SEED', 'Invalid world seed.');
    this.#data = { version: 1, seed, salt: randomBytes(32).toString('hex'), id: randomUUID(), revision: 0, observations: [], journal: [], predictions: [], turn: 0 };
    this.#log('system', 'system', 'We have arrived on an unfamiliar island. Let us find the conditions that bring its plants back to life.');
  }
  #model() { return CANDIDATES[Number.parseInt(hash(this.#data.seed).slice(0, 8), 16) % CANDIDATES.length]!; }
  #opening() { return JSON.stringify({ version: 1, seed: this.#data.seed, salt: this.#data.salt, model: this.#model() }); }
  #log(kind: JournalEntry['kind'], agentId: JournalEntry['agentId'], text: string) {
    const sequence = this.#data.journal.length + 1;
    this.#data.journal.push({ id: `entry-${sequence}`, sequence, kind, agentId, text });
  }
  // PRIVATE persistence: never return this value in an HTTP response.
  serialize(): unknown { return structuredClone(this.#data); }
  static restore(raw: unknown): Expedition {
    if (!raw || typeof raw !== 'object') throw new ExpeditionError('BAD_SNAPSHOT', 'The world snapshot is invalid.');
    const s = raw as Snapshot;
    if (s.version !== 1 || typeof s.seed !== 'string' || !s.seed || typeof s.salt !== 'string' || !/^[a-f0-9]{64}$/.test(s.salt) || typeof s.id !== 'string' || !Number.isInteger(s.revision) || s.revision < 0 || !Number.isInteger(s.turn) || s.turn < 0 || !Array.isArray(s.observations) || s.observations.length > INITIAL_CREDITS || !Array.isArray(s.journal) || !Array.isArray(s.predictions)) throw new ExpeditionError('BAD_SNAPSHOT', 'The world snapshot is invalid.');
    const restored = new Expedition(s.seed);
    const seen = new Set<string>();
    for (const o of s.observations) {
      const c = validateConditions(o.conditions);
      const key = conditionKey(c);
      if (seen.has(key) || heldout.has(key) || o.cost !== COST || !['ada', 'kepler', 'lin', 'human', 'imd'].includes(o.agentId) || !o.outcome || !sameOutcome(modelOutcome(restored.#model(), c), o.outcome)) throw new ExpeditionError('BAD_SNAPSHOT', 'The snapshot contains invalid observations.');
      seen.add(key);
    }
    const candidates = candidatesFor(s.observations);
    if (s.predictions.length && (s.predictions.length !== HOLDOUT.length || !canPredict(candidates) || s.predictions.some((p, i) => conditionKey(validateConditions(p.conditions)) !== conditionKey(HOLDOUT[i]!) || !sameOutcome(p.predicted, modelOutcome(candidates[0]!, HOLDOUT[i]!)) || !sameOutcome(p.actual, modelOutcome(restored.#model(), HOLDOUT[i]!)) || p.correct !== sameOutcome(p.predicted, p.actual)))) throw new ExpeditionError('BAD_SNAPSHOT', 'The snapshot contains invalid predictions.');
    restored.#data = structuredClone(s);
    const records = s.researchRequests ?? [];
    if (!Array.isArray(records) || records.length > 16 || Buffer.byteLength(JSON.stringify(records)) > 2 * 1024 * 1024) throw new ExpeditionError('BAD_SNAPSHOT', 'Research history exceeds its storage limit.');
    const identities = new Set<string>();
    for (const record of records) {
      if (!record || typeof record.id !== 'string' || !/^[a-f0-9-]{36}$/i.test(record.id) || identities.has(record.id) || record.expeditionId !== s.id || record.worldCommitment !== restored.state().commitment || !Number.isSafeInteger(record.revision) || record.revision < 0 || record.revision > s.revision || typeof record.hypothesis !== 'string' || normalizeHypothesis(record.hypothesis) !== record.hypothesis || !['prepared', 'submitted', 'pending', 'verified', 'applied', 'failed', 'stale'].includes(record.status) || !Number.isFinite(record.preparedAt) || !record.input || researchBodyHash(record.input) !== record.bodyHash) throw new ExpeditionError('BAD_SNAPSHOT', 'The snapshot contains invalid research provenance.');
      if (record.decision) parseResearchDecision(record.decision, record);
      if (record.txHistory !== undefined && (!Array.isArray(record.txHistory) || record.txHistory.length > 8 || record.txHistory.some(attempt => !attempt || !/^0x[0-9a-f]{64}$/i.test(attempt.txHash) || !Number.isFinite(attempt.attachedAt) || !Number.isFinite(attempt.replacedAt) || (attempt.error !== undefined && (typeof attempt.error !== 'string' || attempt.error.length > 1000))))) throw new ExpeditionError('BAD_SNAPSHOT', 'Research transaction history is invalid.');
      if (['verified', 'applied'].includes(record.status) && (!record.decision || !record.evidence || !record.txHash || !record.artifactHash)) throw new ExpeditionError('BAD_SNAPSHOT', 'Verified research is missing its evidence.');
      identities.add(record.id);
    }
    // Project an empty history for legacy snapshots without rewriting their bytes.
    if (s.researchRequests !== undefined) restored.#data.researchRequests = structuredClone(records);
    return restored;
  }
  state(): ExpeditionState {
    const observations = this.#data.observations.map(o => ({ ...o, note: englishText(o.note) }));
    const candidates = candidatesFor(observations);
    const spent = observations.length * COST;
    const predictions = this.#data.predictions;
    const ready = canPredict(candidates);
    const restored = predictions.length === HOLDOUT.length && predictions.every(p => p.correct);
    const team = researchers().map(r => {
      const own = observations.filter(o => o.agentId === r.id);
      return { ...r, experiments: own.length, spent: own.length * COST, thought: own.at(-1)?.note ?? r.thought };
    });
    return structuredClone({
      id: this.#data.id, revision: this.#data.revision, commitment: `0x${hash(this.#opening())}`,
      phase: restored ? 'restored' : ready ? 'ready' : spent >= INITIAL_CREDITS ? 'exhausted' : observations.length ? 'exploring' : 'unexplored',
      credits: INITIAL_CREDITS - spent, spent, initialCredits: INITIAL_CREDITS,
      researchers: team, observations, hypotheses: hypothesesFor(observations), journal: this.#data.journal.map(entry => ({ ...entry, text: englishText(entry.text) })),
      candidateCount: candidates.length, initialCandidateCount: CANDIDATES.length,
      progress: restored ? 100 : observations.length ? Math.min(90, Math.round((1 - Math.log2(Math.max(1, candidates.length)) / Math.log2(CANDIDATES.length)) * 90)) : 0,
      predictions, holdoutScore: predictions.length ? Math.round(100 * predictions.filter(p => p.correct).length / predictions.length) : null,
      restored, engine: 'local', researchRequests: this.#data.researchRequests ?? [],
      availableExperiments: TRAINING.filter(c => !observations.some(o => conditionKey(o.conditions) === conditionKey(c))),
      restoration: restored ? { conditions: { ...candidates[0]! }, outcome: modelOutcome(this.#model(), candidates[0]!) } : null,
    } as ExpeditionState);
  }
  #experiment(input: Conditions, actor: Observation['agentId'], reason: string): ExpeditionState {
    const conditions = validateConditions(input);
    if (heldout.has(conditionKey(conditions))) throw new ExpeditionError('HELD_OUT', 'This experiment is reserved for the final prediction check. Choose another combination.');
    if (this.#data.observations.some(o => conditionKey(o.conditions) === conditionKey(conditions))) throw new ExpeditionError('DUPLICATE_EXPERIMENT', 'This experiment is already in shared memory. No credits were spent.');
    if (this.#data.predictions.length) throw new ExpeditionError('EXPEDITION_COMPLETE', 'Validation is complete. Start a new expedition.');
    if (this.#data.observations.length * COST >= INITIAL_CREDITS) throw new ExpeditionError('BUDGET_EXHAUSTED', 'The experiment budget is exhausted.');
    const before = hypothesesFor(this.#data.observations);
    const previousCount = candidatesFor(this.#data.observations).length;
    const outcome = modelOutcome(this.#model(), conditions);
    const sequence = this.#data.observations.length + 1;
    this.#data.observations.push({ id: `observation-${sequence}`, sequence, agentId: actor, conditions, outcome, cost: COST, note: reason });
    this.#data.revision++;
    this.#log('observation', actor, `Experiment ${sequence}: ${outcome.survived ? 'the plant survived' : 'the plant did not survive'}, growth ${outcome.growth}/100. Spent 2 credits.`);
    const remaining = candidatesFor(this.#data.observations).length;
    if (remaining < previousCount) this.#log('hypothesis', actor, `Possible explanations narrowed: ${previousCount} → ${remaining}.`);
    hypothesesFor(this.#data.observations).forEach((h, i) => {
      if (h.status === 'supported' && before[i]?.status !== 'supported') this.#log('discovery', h.agentId, `${h.title}. ${h.description}`);
    });
    return this.state();
  }
  experiment(input: Conditions, actor: 'human' | 'imd' = 'human', reason = 'Experiment selected manually.'): ExpeditionState {
    if (actor !== 'human' && actor !== 'imd') throw new ExpeditionError('BAD_ACTOR', 'Unknown experiment source.');
    if (typeof reason !== 'string' || reason.length > 2000) throw new ExpeditionError('BAD_INPUT', 'The experiment explanation must be a string of at most 2,000 characters.');
    return this.#experiment(input, actor, reason);
  }
  #research(id: string): ImdResearchRecord {
    const record = this.#data.researchRequests?.find(r => r.id === id);
    if (!record) throw new ExpeditionError('RESEARCH_NOT_FOUND', 'Research request not found.', 404);
    return record;
  }
  recordResearchPreflight(preflight: ImdPreflight, hypothesis?: string): ImdResearchRecord {
    const state = this.state();
    const question = normalizeHypothesis(hypothesis ?? preflight.hypothesis);
    if (!preflight.researchId || !/^[a-f0-9-]{36}$/i.test(preflight.researchId) || preflight.expeditionId !== state.id || preflight.worldCommitment !== state.commitment || preflight.revision !== state.revision || preflight.hypothesis !== question || preflight.check?.action !== 'job.open' || preflight.check.blockers?.length !== 0 || Date.now() - preflight.checkedAt > 300_000 || preflight.checkedAt > Date.now() + 30_000 || researchBodyHash(preflight.input) !== researchBodyHash(buildResearchJob(state, question, preflight.researchId))) throw new ExpeditionError('STALE_RESEARCH', 'Run a fresh free preflight for this hypothesis and world revision.', 409);
    const history = this.#data.researchRequests ??= [];
    if (history.some(r => r.id === preflight.researchId)) throw new ExpeditionError('DUPLICATE_RESEARCH', 'This research preflight is already recorded.', 409);
    if (history.length >= 16) throw new ExpeditionError('RESEARCH_LIMIT', 'This expedition already has 16 research requests. Start another expedition.', 409);
    const record: ImdResearchRecord = { id: preflight.researchId, expeditionId: state.id, worldCommitment: state.commitment, revision: state.revision, hypothesis: question, input: structuredClone(preflight.input), bodyHash: researchBodyHash(preflight.input), preparedAt: preflight.checkedAt, network: structuredClone(preflight.network), status: 'prepared' };
    if (preflight.registryAddress) {
      if (!/^0x[0-9a-f]{40}$/i.test(preflight.registryAddress) || !/^0x[0-9a-f]{64}$/i.test(preflight.registryCodeHash ?? '')) throw new ExpeditionError('BAD_REGISTRY', 'The registry preflight is missing its runtime code identity.');
      record.registryAddress = preflight.registryAddress; record.registryCodeHash = preflight.registryCodeHash;
    }
    history.push(record);
    this.#log('research', 'system', `Free IMD preflight recorded (${record.id}). No IMD request was purchased or experiment executed.`);
    return structuredClone(record);
  }
  attachResearchTransaction(id: string, txHash: string, options: { replace?: boolean } = {}): ImdResearchRecord {
    const record = this.#research(id);
    if (!/^0x[a-f0-9]{64}$/i.test(txHash)) throw new ExpeditionError('BAD_TRANSACTION', 'Provide an Ethereum transaction hash.');
    const different = record.txHash && record.txHash.toLowerCase() !== txHash.toLowerCase();
    if (different && !options.replace) throw new ExpeditionError('TRANSACTION_CONFLICT', 'This request is already bound to another transaction.', 409);
    if (different && (['verified', 'applied', 'stale'].includes(record.status) || record.evidence || record.decision || record.artifactHash)) throw new ExpeditionError('TRANSACTION_VERIFIED', 'An authenticated research transaction cannot be replaced.', 409);
    if (different && (record.txHistory?.length ?? 0) >= 8) throw new ExpeditionError('TRANSACTION_HISTORY_LIMIT', 'This request has reached the limit of eight transaction replacements.', 409);
    if ((this.#data.researchRequests ?? []).some(r => r.id !== id && r.txHash?.toLowerCase() === txHash.toLowerCase())) throw new ExpeditionError('TRANSACTION_REUSED', 'This transaction is already attached to another request.', 409);
    if (record.txHash && !different) return structuredClone(record);
    if (different) {
      (record.txHistory ??= []).push({ txHash: record.txHash!, attachedAt: record.txAttachedAt ?? record.preparedAt, replacedAt: Date.now(), ...(record.error ? { error: record.error } : {}) });
      this.#log('research', 'system', `Unverified transaction for research ${id} explicitly replaced. Previous hash: ${record.txHash}.`);
      record.jobId = undefined; record.checkedAt = undefined;
    }
    record.txHash = txHash as `0x${string}`; record.txAttachedAt = Date.now(); record.status = 'submitted'; record.error = undefined;
    this.#log('research', 'system', `Ethereum transaction attached to research ${id}. IMD provenance is not yet verified.`);
    return structuredClone(record);
  }
  async refreshResearchRequest(id: string, options: ResearchEvidenceOptions = {}): Promise<ImdResearchRecord> {
    const record = this.#research(id);
    if (record.status === 'applied') return structuredClone(record);
    const checkingHash = record.txHash;
    try {
      const update = await verifyResearchEvidence(structuredClone(record), options);
      if (this.#research(id).status === 'applied' || record.txHash !== checkingHash) return structuredClone(this.#research(id));
      Object.assign(record, update);
      if (record.status === 'verified' && this.#data.revision !== record.revision) { record.status = 'stale'; record.error = 'The world revision changed. Prepare a new research request before another IMD experiment.'; }
    } catch (error) {
      if (this.#research(id).status === 'applied' || record.txHash !== checkingHash) return structuredClone(this.#research(id));
      record.checkedAt = Date.now(); record.error = error instanceof Error ? error.message.slice(0, 1000) : 'Research verification failed.';
      // Transport errors are retryable; they never fabricate a failed experiment.
      // Invalidate an earlier verification so a failed recheck cannot remain applyable.
      if (record.status === 'verified') record.status = 'pending';
    }
    return structuredClone(record);
  }
  applyResearchRequest(id: string): ExpeditionState {
    const record = this.#research(id);
    if (record.status === 'applied') throw new ExpeditionError('RESEARCH_ALREADY_APPLIED', 'This research experiment has already been executed.', 409);
    if (record.status !== 'verified' || !record.decision || !record.evidence || !record.artifactHash) throw new ExpeditionError('RESEARCH_UNVERIFIED', 'Verify the original IMD transaction and accepted artifact first.', 409);
    if (this.#data.revision !== record.revision || this.state().commitment !== record.worldCommitment) throw new ExpeditionError('STALE_RESEARCH', 'This research decision belongs to an earlier world revision.', 409);
    const decision = parseResearchDecision(record.decision, record);
    this.#experiment(decision.conditions, 'imd', decision.reason);
    record.status = 'applied'; record.appliedRevision = this.#data.revision;
    this.#log('research', 'imd', `Verified IMD decision applied (${record.id}; artifact SHA-256 ${record.artifactHash}). Hypothesis assessment: ${decision.hypothesisAssessment}`);
    return this.state();
  }
  step(): ExpeditionState {
    const state = this.state();
    if (state.phase === 'ready' || state.phase === 'restored') return state;
    if (state.credits < COST) throw new ExpeditionError('BUDGET_EXHAUSTED', 'The experiment budget is exhausted.');
    const decision = decideExperiment(this.#data.observations, this.#data.turn);
    if (!decision) throw new ExpeditionError('NO_EXPERIMENTS', 'There are no available experiments left.');
    const result = this.#experiment(decision.conditions, decision.agentId, decision.reason);
    this.#data.turn++;
    return result;
  }
  predict(): ExpeditionState {
    if (this.#data.predictions.length) return this.state();
    const candidates = candidatesFor(this.#data.observations);
    if (!canPredict(candidates)) throw new ExpeditionError('NOT_READY', 'Collect more observations first: the remaining models still disagree on their predictions.');
    // Commit every prediction before requesting any actual held-out outcome.
    const committed = HOLDOUT.map(conditions => ({ conditions: { ...conditions }, predicted: modelOutcome(candidates[0]!, conditions) }));
    this.#data.predictions = committed.map(p => {
      const actual = modelOutcome(this.#model(), p.conditions);
      return { ...p, actual, correct: sameOutcome(p.predicted, actual) };
    });
    this.#data.revision++;
    this.#log('prediction', 'system', `Independent validation: ${this.#data.predictions.filter(p => p.correct).length}/${HOLDOUT.length} exact predictions. Held-out results were not added to the training observations.`);
    return this.state();
  }
  reveal() {
    if (!this.state().restored) throw new ExpeditionError('NOT_COMPLETE', 'The world rules can be revealed after final validation.');
    const opening = this.#opening();
    return { opening, commitment: `0x${hash(opening)}`, algorithm: 'SHA-256', matches: this.state().commitment === `0x${hash(opening)}` };
  }
}
