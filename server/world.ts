const INITIAL_CREDITS = 40;
const COST = 2;
const hash = (value: string) => createHash('sha256').update(value).digest('hex');
const heldout = new Set(HOLDOUT.map(conditionKey));
export class ExpeditionError extends Error {
  constructor(public code: string, message: string, public status = 400) { super(message); this.name = 'ExpeditionError'; }
}
function validateConditions(input: unknown): Conditions {
  if (!input || typeof input !== 'object' || Array.isArray(input)) throw new ExpeditionError('BAD_INPUT', 'Provide all four experiment conditions.');
  const c = input as Record<string, unknown>;
  if (Object.keys(c).length !== 4 || typeof c.water !== 'boolean' || !['none', 'basalt', 'quartz'].includes(String(c.mineral)) || !['amber', 'blue'].includes(String(c.light)) || !['cool', 'warm'].includes(String(c.temperature))) throw new ExpeditionError('BAD_INPUT', 'Invalid experiment conditions.');
  return { water: c.water, mineral: c.mineral as Conditions['mineral'], light: c.light as Conditions['light'], temperature: c.temperature as Conditions['temperature'] };
}
interface Snapshot {
  version: 1; seed: string; salt: string; id: string; revision: number;
  observations: Observation[]; journal: JournalEntry[]; predictions: ExpeditionState['predictions']; turn: number;
  researchRequests?: ImdResearchRecord[];
}

